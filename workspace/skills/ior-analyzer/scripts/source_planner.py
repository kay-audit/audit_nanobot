"""Планирование выборки данных ИОР — чистые функции без внешних зависимостей.

Вынесено из ``ior_reports.py``, чтобы правила выбора источника можно было
покрыть обычными юнит-тестами: модуль не тянет pandas/Greenplum/LLM.

Две задачи:

* ``has_comparative_threshold`` — понимает, задаёт ли фраза числовой порог.
  Сравнительные слова сами по себе («на какую сумму больше всего») фильтром
  не являются: уводили навык с корректного пресетного запроса на
  сгенерированный, который возвращал ноль строк.
* ``plan_widening_presets`` — порядок расширения источника, когда выборка
  оказалась пустой: сначала предметный пресет, затем базовая витрина
  инцидентов. Пустой результат не равен «данных нет».
"""

from __future__ import annotations

import re

# Базовый пресет: витрина инцидентов без соединения с таблицами последствий.
BASE_PRESET = "ior_hypothesis"

# Сравнительный порог в свободном тексте: «больше 100000», «свыше 10 млн».
# Без числа после сравнительного слова это просто оборот речи, а не фильтр.
COMPARATIVE_WITH_NUMBER = re.compile(
    r"(?:более|больше|свыше|выше|не\s+менее|от)\s*[-+]?\d[\d\s.,]*",
    re.IGNORECASE,
)


def has_comparative_threshold(user_prompt: str) -> bool:
    """True, если в запросе есть сравнение с числовым порогом."""
    return bool(COMPARATIVE_WITH_NUMBER.search(user_prompt or ""))


def plan_widening_presets(preset: str, has_filters: bool) -> list[str]:
    """Порядок пресетов для расширения источника после пустой выборки.

    Пустой результат не означает, что в базе нет данных: слишком узкий
    WHERE или ошибочно выбранный предметный пресет дают ноль строк при
    непустой витрине.

    Важно различать, **что именно уже выполнялось**:

    * ``has_filters=True`` — выполнялся сгенерированный запрос с LLM-WHERE,
      готовый запрос пресета не выполнялся вовсе. Поэтому возвращаем и его:
      это единственный способ снять слишком узкий фильтр;
    * ``has_filters=False`` — выполнялся уже готовый запрос пресета, и
      повторять его бессмысленно.

    Args:
        preset: Имя разрешённого пресета.
        has_filters: Был ли выполнен сгенерированный запрос вместо пресетного.

    Returns:
        Список имён пресетов в порядке попыток; пустой список, если
        расширять нечего.
    """
    steps: list[str] = []
    if has_filters and preset:
        steps.append(preset)
    if preset != BASE_PRESET and BASE_PRESET not in steps:
        steps.append(BASE_PRESET)
    return steps